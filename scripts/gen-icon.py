#!/usr/bin/env python3
"""Regenerate the launcher icon drawables from art/lurkr.svg (512px pixel art made of <rect>s).

usage: scripts/gen-icon.py
"""
import os
import re

root = os.path.join(os.path.dirname(__file__), "..")
svg = open(os.path.join(root, "art/lurkr.svg")).read()
# x and y may be left out (SVG defaults them to 0)
rects = [(x or "0", y or "0", w, h, c) for x, y, w, h, c in
         re.findall(r'<rect (?:x="(\d+)" )?(?:y="(\d+)" )?width="(\d+)" height="(\d+)" fill="([^"]+)"/>', svg)]

by_color = {}
for x, y, w, h, c in rects:
    by_color.setdefault(c.lower(), []).append(f"M{x},{y}h{w}v{h}h-{w}z")

# 512px art -> ART_DP inside the 108dp adaptive canvas (the safe circle is 66dp; smaller = more margin)
ART_DP = 52


def doc(paths, comment, art_dp=ART_DP, up=0):
    s = art_dp / 512
    t = (108 - art_dp) / 2
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {comment} -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
        f'    <group android:translateX="{t}" android:translateY="{t - up}" android:scaleX="{s:.6f}" android:scaleY="{s:.6f}">',
    ]
    out += [f'        <path android:fillColor="{color}" android:pathData="{d}" />' for color, d in paths]
    out += ["    </group>", "</vector>", ""]
    return "\n".join(out)


res = os.path.join(root, "app/src/main/res/drawable")
fg = [("@color/lurkr_black", "".join(by_color["black"])), ("@color/lurkr_blue", "".join(by_color["#0000ee"]))]
open(os.path.join(res, "ic_launcher_foreground.xml"), "w").write(
    doc(fg, "Generated from art/lurkr.svg by scripts/gen-icon.py. Do not edit by hand."))
mono = [("#FFFFFFFF", "".join(by_color["black"]) + "".join(by_color["#0000ee"]))]
open(os.path.join(res, "ic_launcher_monochrome.xml"), "w").write(
    doc(mono, "Themed-icon version of art/lurkr.svg (all ink in one colour). Generated by scripts/gen-icon.py."))
# The splash screen shows only the middle 72dp of the 108dp canvas, in a circle: the face drawn bigger there,
# nudged up 2dp so the face (not the shoulders' line) sits in the middle
open(os.path.join(res, "splash_icon.xml"), "w").write(
    doc(fg, "Splash-screen version of art/lurkr.svg (bigger). Generated by scripts/gen-icon.py.", art_dp=56, up=2))
print({k: len(v) for k, v in by_color.items()})

# The README's logo: The face on a white circle, at 80% (as Lurkr draws its own icon in the app), so it shows on
# GitHub's dark theme too
inner = "\n".join(f'    <path fill="{"#0000EE" if c == "#0000ee" else "black"}" d="{"".join(by_color[c])}"/>' for c in ("black", "#0000ee"))
open(os.path.join(root, "art/lurkr-round.svg"), "w").write(
    '<svg width="512" height="512" viewBox="0 0 512 512" xmlns="http://www.w3.org/2000/svg">\n'
    "  <!-- Generated from art/lurkr.svg by scripts/gen-icon.py. Do not edit by hand. -->\n"
    '  <circle cx="256" cy="256" r="256" fill="white"/>\n'
    '  <g transform="translate(51.2 51.2) scale(0.8)">\n' + inner + "\n  </g>\n</svg>\n")
